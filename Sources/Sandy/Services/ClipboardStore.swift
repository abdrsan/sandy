import AppKit

struct ClipItem: Identifiable, Equatable {
    enum Payload: Equatable {
        case text(String)
        case file(URL)
        /// A copied picture that went to the screenshot vault — history keeps
        /// a marker row instead of the bytes.
        case image(URL)
    }

    let id = UUID()
    let payload: Payload
    let date: Date
    /// Pinned entries never leave: not by the limit, not by clear-all.
    var pinned = false

    var preview: String {
        switch payload {
        case .text(let string):
            return string.trimmingCharacters(in: .whitespacesAndNewlines)
        case .file(let url):
            return url.lastPathComponent
        case .image(let url):
            return "\(localized("Image")) — \(url.lastPathComponent)"
        }
    }

    var symbol: String {
        switch payload {
        case .text(let string):
            if string.hasPrefix("http://") || string.hasPrefix("https://") { return "link" }
            return "text.alignleft"
        case .file:
            return "doc"
        case .image:
            return "photo"
        }
    }

    /// True when a file-backed entry points at a path that is gone.
    var fileMissing: Bool {
        switch payload {
        case .file(let url), .image(let url):
            return !FileManager.default.fileExists(atPath: url.path)
        case .text:
            return false
        }
    }

    static func == (lhs: ClipItem, rhs: ClipItem) -> Bool { lhs.payload == rhs.payload }
}

/// Polls the general pasteboard's change counter. Cheap: one integer read
/// twice a second, and nothing at all is read until the counter moves.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    /// Raised for image data on the pasteboard — a screenshot taken straight to
    /// the clipboard, which would otherwise vanish after one paste.
    var onImage: ((Data) -> Void)?

    /// Whether images are worth reading at all. Asked before the TIFF → PNG
    /// encode, not after: with screenshot saving switched off, a copied picture
    /// would otherwise be encoded in full and then thrown away.
    var wantsImages: () -> Bool = { true }

    private var timer: Timer?
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var imageGeneration = 0
    /// Live read: the setting can move while the app runs.
    private var limit: Int { max(1, ConfigStore.shared.clipboardLimit) }
    private let saves = DebouncedWrite()
    /// Types an app sets to keep a copy out of history tools. Presence is what
    /// counts, not content: a type can be declared with data that is still on
    /// its way, and asking for the bytes would then answer nil for a password
    /// that is about to arrive. `ConcealedType` is what password managers set;
    /// the other two mark copies made by a machine rather than by a hand.
    private let optOut: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        loadIfEnabled()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        // The half-second is a ceiling, not a beat: nobody notices a copy
        // landing in history a fifth of a second late, and the slack lets the
        // system fold this wake-up into others.
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        imageGeneration += 1
        timer?.invalidate()
        timer = nil
    }

    /// Clear-all keeps pinned rows — that is the whole point of pinning.
    func clear() {
        items.removeAll { !$0.pinned }
        scheduleSave()
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        scheduleSave()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        scheduleSave()
    }

    /// Puts an entry back on the pasteboard without re-recording it.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.payload {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .file(let url), .image(let url):
            pasteboard.writeObjects([url as NSURL])
        }
        lastChangeCount = pasteboard.changeCount
        // Freshly used entries bubble to the top.
        if let index = items.firstIndex(where: { $0.id == item.id }), index != 0 {
            items.remove(at: index)
            items.insert(item, at: 0)
        }
    }

    func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        imageGeneration += 1
        lastChangeCount = pasteboard.changeCount

        // The app the copy was made in is the frontmost one — Sandy's panel
        // never activates, so a copy off a snippet still names its own mark.
        if let owner = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           ConfigStore.shared.clipboardExcludedApps.contains(owner) { return }
        guard pasteboard.availableType(from: optOut) == nil else { return }
        // Our own write — copying a screenshot back out of the shelf must not
        // save it to disk all over again.
        guard pasteboard.data(forType: .sandyInternal) == nil else { return }

        // A copied file arrives as a URL, not as image data, so URLs win first.
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
           let url = urls.first {
            record(ClipItem(payload: .file(url), date: Date()))
            return
        }

        if wantsImages() {
            if let png = pngFromPasteboard(pasteboard) {
                onImage?(png)
                // A copy that carries both a picture and a string — text off
                // a page, a chat message with an inline image — used to keep
                // only the picture and drop the text entirely.
                recordText(from: pasteboard)
                return
            }

            // A copy made on the phone arrives in two parts: macOS puts the
            // type on the pasteboard the moment the phone announces it, and
            // the picture itself is still coming over the air. So the counter
            // can move while there are no bytes to read yet — and reading once
            // would drop the screenshot for good, because the counter has
            // already been marked as seen. Wait for it instead.
            if pasteboard.availableType(from: [.png, .tiff]) != nil {
                awaitImage(at: pasteboard.changeCount, attempt: 0, generation: imageGeneration)
                return
            }
        }

        recordText(from: pasteboard)
    }

    private func recordText(from pasteboard: NSPasteboard) {
        guard let string = pasteboard.string(forType: .string),
              !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        record(ClipItem(payload: .text(string), date: Date()))
    }

    /// Checks back until the promised picture has actually arrived.
    ///
    /// Gives up after a few seconds, and stops the moment the pasteboard moves
    /// on: a copy made in the meantime is the newer intention, and finishing a
    /// transfer the user has already replaced would put the wrong thing on the
    /// shelf.
    private func awaitImage(at changeCount: Int, attempt: Int, generation: Int) {
        guard generation == imageGeneration, wantsImages() else { return }
        // Out of patience. Something declared a picture and never produced one,
        // so fall back to what else was on the pasteboard — otherwise a copy
        // that merely offered an image alongside its text would go unrecorded.
        guard attempt < 12 else {
            guard pasteboard.changeCount == changeCount else { return }
            recordText(from: pasteboard)
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
            MainActor.assumeIsolated {
                guard let self else { return }
                guard generation == self.imageGeneration, self.wantsImages() else { return }
                let pasteboard = self.pasteboard
                guard pasteboard.changeCount == changeCount else { return }
                if let png = self.pngFromPasteboard(pasteboard) {
                    self.onImage?(png)
                    self.recordText(from: pasteboard)
                    return
                }
                self.awaitImage(at: changeCount, attempt: attempt + 1, generation: generation)
            }
        }
    }

    /// Screenshots land as PNG; other apps often offer only TIFF.
    private func pngFromPasteboard(_ pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func record(_ item: ClipItem) {
        items.removeAll { $0 == item }
        items.insert(item, at: 0)
        while items.count > limit, let last = items.lastIndex(where: { !$0.pinned }) {
            items.remove(at: last)
        }
        scheduleSave()
    }

    // MARK: - Persistence

    /// Off by default: whatever lands in a clipboard history is by nature
    /// worth hiding, so keeping it past a relaunch is a deliberate choice.
    /// The file is mode 0600 in the app's own support folder.
    private struct StoredClip: Codable {
        var kind: String
        var value: String
        var date: Date
        var pinned: Bool?
    }

    private static var file: URL { Support.file("clipboard.json") }

    private func loadIfEnabled() {
        guard ConfigStore.shared.clipboardPersist,
              let data = try? Data(contentsOf: Self.file),
              let stored = try? JSONDecoder().decode([StoredClip].self, from: data) else { return }
        items = stored.sorted { $0.date > $1.date }.prefix(limit).compactMap { clip in
            var item: ClipItem
            switch clip.kind {
            case "text": item = ClipItem(payload: .text(clip.value), date: clip.date)
            case "file": item = ClipItem(payload: .file(URL(fileURLWithPath: clip.value)), date: clip.date)
            case "image": item = ClipItem(payload: .image(URL(fileURLWithPath: clip.value)), date: clip.date)
            default: return nil
            }
            item.pinned = clip.pinned ?? false
            return item
        }
    }

    private func scheduleSave() {
        guard ConfigStore.shared.clipboardPersist else { return }
        saves.schedule { [weak self] in self?.persist() }
    }

    private func persist() {
        guard ConfigStore.shared.clipboardPersist else { return }
        let stored = items.map { item -> StoredClip in
            switch item.payload {
            case .text(let string): return StoredClip(kind: "text", value: string, date: item.date, pinned: item.pinned)
            case .file(let url): return StoredClip(kind: "file", value: url.path, date: item.date, pinned: item.pinned)
            case .image(let url): return StoredClip(kind: "image", value: url.path, date: item.date, pinned: item.pinned)
            }
        }
        do {
            try JSONEncoder().encode(stored).write(to: Self.file, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: Self.file.path)
        } catch {
            NSLog("Sandy: cannot write clipboard.json: \(error.localizedDescription)")
        }
    }

    /// Writes whatever is pending — for quit, where the debounce would lose it.
    func flush() { saves.flush() }

    /// Records that an image was just saved to the vault, so the history shows
    /// a marker row next to the text it may have carried.
    func noteImage(_ url: URL) {
        record(ClipItem(payload: .image(url), date: Date()))
    }
}
