@MainActor
struct CurrencyAndTranslationTests {
    @Test func amountsAcceptLocalizedGroupingAndRejectInvalidNumbers() throws {
        for input in ["1 234,56", "1\u{00a0}234,56", "1\u{202f}234,56", "1,234.56", "1.234,56"] {
            let value = try #require(CurrencyStore.parse(input))
            #expect(abs(value - 1234.56) < 0.000001)
        }
        #expect(CurrencyStore.parse(" -12,5 ") == -12.5)
        #expect(CurrencyStore.parse("0") == 0)
        for invalid in ["", " ", ".", ",", "NaN", "inf", "1e999", "12 USD", "1\n2", "1.2.3"] {
            #expect(CurrencyStore.parse(invalid) == nil)
        }
    }

    @Test func translationDirectionKeepsItsDocumentedEnglishRussianPair() {
        #expect(Translator.route(for: "Привет").source == Translator.russian)
        #expect(Translator.route(for: "Привет").target == Translator.english)
        #expect(Translator.route(for: "Hello").source == Translator.english)
        #expect(Translator.route(for: "Hello").target == Translator.russian)
    }

    @Test func currencyFormattingStaysFiniteAndUsefulForSmallAmounts() {
        #expect(!CurrencyStore.format(0.00001234).isEmpty)
        #expect(!CurrencyStore.format(1234.56).isEmpty)
        #expect(CurrencyStore.parse(CurrencyStore.format(1234.56)) == 1234.56)
    }
}

@MainActor
struct ClipboardStoreTests {
    private func board() -> NSPasteboard { NSPasteboard.withUniqueName() }

    private func write(_ text: String, to board: NSPasteboard) {
        board.clearContents()
        board.setString(text, forType: .string)
    }

    @Test func textHistoryDeduplicatesCapsAndDoesNotRecordItsOwnCopies() throws {
        let board = board()
        defer { board.releaseGlobally() }
        let store = ClipboardStore(pasteboard: board)
        store.wantsImages = { false }
        for i in 0..<45 { write("item \(i)", to: board); store.poll() }
        #expect(store.items.count == 40)
        #expect(store.items.first?.payload == .text("item 44"))
        write("item 10", to: board)
        store.poll()
        #expect(store.items.count == 40)
        #expect(store.items.first?.payload == .text("item 10"))
        try #require(store.items.count > 4)
        let item = store.items[4]
        store.copy(item)
        store.poll()
        #expect(store.items.count == 40)
        #expect(store.items.first?.id == item.id)
        #expect(board.string(forType: .string) == item.preview)
        store.remove(item)
        #expect(!store.items.contains(where: { $0.id == item.id }))
        store.clear()
        #expect(store.items.isEmpty)
    }

    @Test func privateAndInternalCopiesAreExcludedBeforeReadingContents() {
        let board = board()
        defer { board.releaseGlobally() }
        let store = ClipboardStore(pasteboard: board)
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                     "org.nspasteboard.AutoGeneratedType", NSPasteboard.PasteboardType.sandyInternal.rawValue] {
            write("do not keep", to: board)
            board.setData(Data(), forType: .init(type))
            store.poll()
        }
        #expect(store.items.isEmpty)
        write("   \n  ", to: board)
        store.poll()
        #expect(store.items.isEmpty)
    }

    @Test func fileReferencesTakePriorityAndImageSavingCanBeDisabled() {
        let board = board()
        defer { board.releaseGlobally() }
        let store = ClipboardStore(pasteboard: board)
        var images = 0
        store.onImage = { _ in images += 1 }
        let file = URL(fileURLWithPath: "/tmp/sandy-test-file.txt")
        board.clearContents()
        board.writeObjects([file as NSURL])
        board.setData(Data([1, 2, 3]), forType: .png)
        store.poll()
        #expect(store.items.first?.payload == .file(file))
        #expect(images == 0)
        board.clearContents()
        board.setData(Data([1, 2, 3]), forType: .png)
        store.poll()
        #expect(images == 1)
        store.wantsImages = { false }
        board.clearContents()
        board.setData(Data([1, 2, 3]), forType: .png)
        board.setString("image caption", forType: .string)
        store.poll()
        #expect(images == 1)
        #expect(store.items.first?.payload == .text("image caption"))
    }

    @Test func delayedImagesDoNotArriveAfterMonitoringStops() async throws {
        let board = board()
        defer { board.releaseGlobally() }
        let store = ClipboardStore(pasteboard: board)
        var images = 0
        store.onImage = { _ in images += 1 }
        board.declareTypes([.png], owner: nil)
        store.poll()
        store.stop()
        board.setData(Data([1, 2, 3]), forType: .png)
        try await Task.sleep(for: .milliseconds(650))
        #expect(images == 0)
    }
}

@MainActor
struct ShelfStoreTests {
    private func withShelf(_ body: (ShelfStore, URL, NSPasteboard) throws -> Void) throws {
        let domain = "SandyTests.Shelf.\(UUID().uuidString)"
        let defaults = try #require(UserDefaults(suiteName: domain))
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(domain)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let board = NSPasteboard.withUniqueName()
        defer {
            board.releaseGlobally()
            defaults.removePersistentDomain(forName: domain)
            try? FileManager.default.removeItem(at: directory)
        }
        try body(ShelfStore(defaults: defaults, pasteboard: board), directory, board)
    }

    @Test func selectionCopiesFilesAndReloadClearsObsoleteSelection() throws {
        try withShelf { store, directory, board in
            let first = directory.appendingPathComponent("one.txt")
            let second = directory.appendingPathComponent("two.txt")
            try "one".write(to: first, atomically: true, encoding: .utf8)
            try "two".write(to: second, atomically: true, encoding: .utf8)
            store.add([first, second, first])
            #expect(store.items.count == 2)
            try #require(store.items.count == 2)
            store.select(store.items[0], modifiers: [])
            store.select(store.items[1], modifiers: .command)
            #expect(store.selection.count == 2)
            #expect(Set(store.dragURLs(startingAt: store.items[0])) == Set([first, second]))
            #expect(Set((board.string(forType: .string) ?? "").split(separator: "\n").map(String.init)) == Set([first.path, second.path]))
            #expect(board.data(forType: .sandyInternal) != nil)
            store.load()
            #expect(store.items.count == 2)
            #expect(store.selection.isEmpty)
            store.clear()
            #expect(store.items.isEmpty)
            #expect(FileManager.default.fileExists(atPath: first.path))
            #expect(FileManager.default.fileExists(atPath: second.path))
        }
    }

    @Test func expiredCardsAreRemovedAndLimitNeverLeavesPhantomSelection() throws {
        try withShelf { store, directory, _ in
            let old = directory.appendingPathComponent("old.txt")
            try "old".write(to: old, atomically: true, encoding: .utf8)
            store.add([old])
            store.select(try #require(store.items.first), modifiers: [])
            let extra = (0..<60).map { directory.appendingPathComponent("new-\($0).txt") }
            store.add(extra)
            #expect(store.items.count == 60)
            #expect(store.selection.isEmpty)
            store.refreshFromDisk()
            #expect(store.items.isEmpty)
            #expect(FileManager.default.fileExists(atPath: old.path))
        }
    }
}

@MainActor
struct PrivacyModeTests {
    @Test func coverRevealAndCollapseRespectIndividualSections() {
        var saved: [String] = []
        let store = PrivacyMode(sections: [.notes], save: { saved = $0 })
        #expect(store.hides(.notes, "note"))
        #expect(!store.hides(.clipboard, "clip"))
        store.reveal("note")
        #expect(!store.hides(.notes, "note"))
        store.coverEverything()
        #expect(store.hides(.notes, "note"))
        store.setCoveringAll(true)
        #expect(store.coversAll)
        #expect(Set(saved) == Set(PrivacyMode.Section.allCases.map(\.rawValue)))
        store.toggle("note")
        store.setCoveringAll(false)
        #expect(!store.coversAny)
        #expect(store.revealed.isEmpty)
    }
}

@MainActor
struct TeleprompterStoreTests {
    private func withScript(_ body: (URL) throws -> Void) throws {
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent("sandy-prompter-\(UUID())")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }
        try body(folder.appendingPathComponent("teleprompter.txt"))
    }

    @Test func playbackStopsAtLastLineAndEditingPausesAndPersists() throws {
        try withScript { file in
            let store = TeleprompterStore(file: file, speed: 1, fontSize: 30, saveSettings: { _, _ in })
            store.start()
            #expect(!store.isRunning)
            store.script = "First line\n最後の行"
            store.contentHeight = 120
            store.viewportHeight = 100
            #expect(store.maxOffset == 70)
            store.start()
            store.tick()
            #expect(store.offset > 0)
            store.offset = store.maxOffset - 0.1
            store.tick()
            #expect(store.offset == store.maxOffset)
            #expect(!store.isRunning)
            store.start()
            #expect(store.offset == 0)
            store.script = "New script"
            #expect(!store.isRunning)
            #expect(store.offset == 0)
            store.flush()
            let saved = try String(contentsOf: file, encoding: .utf8)
            #expect(saved == "New script")
        }
    }

    @Test func invalidUTF8IsKeptBeforeSavingNewText() throws {
        try withScript { file in
            let original = Data([0xFF, 0xFE, 0xFD])
            try original.write(to: file)
            let store = TeleprompterStore(file: file, speed: 1, fontSize: 30, saveSettings: { _, _ in })
            store.script = "Replacement"
            store.flush()
            let backups = try FileManager.default.contentsOfDirectory(at: file.deletingLastPathComponent(), includingPropertiesForKeys: nil)
                .filter { $0.lastPathComponent.hasPrefix("teleprompter.unreadable-") }
            #expect(backups.count == 1)
            let backup = try #require(backups.first)
            let preserved = try Data(contentsOf: backup)
            let saved = try String(contentsOf: file, encoding: .utf8)
            #expect(preserved == original)
            #expect(saved == "Replacement")
        }
    }
}
